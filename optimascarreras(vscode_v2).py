"""# Bloque 6: #
Ejecuta la función generar_diagnostico_global, la cual analiza el panel consolidado para evaluar la evolución temporal de la cobertura (conteo de programas por año), detectar anomalías transversales (aranceles en $0, duraciones fuera del rango de 4 a 16 semestres) y medir la permanencia promedio de los programas en el sistema educativo.
"""

def generar_diagnostico_global(df_hist):
    informe = []
    informe.append("============================================================")
    informe.append("=== DIAGNÓSTICO LONGITUDINAL DE LA BASE HISTÓRICA MINEDUC ===")
    informe.append("============================================================\n")

    # 1. Resumen por Año
    informe.append("--- 1. EVOLUCIÓN TEMPORAL DE COBERTURA Y CONTEOS ---")
    resumen_anual = df_hist.groupby("cat_periodo").agg(
        total_programas=("codigo_unico", "count"),
        ingresantes_utilizables=("nuevos_ingresados_provisional", "sum"),
        programas_sin_incidencias=("estado_conteo", lambda s: (s == "Sin incidencias detectadas").sum()),
        programas_pendientes=("estado_conteo", lambda s: (s == "Pendiente de revisión").sum()),
        programas_cero_admision=("estado_conteo", lambda s: (s == "Cero observado: verificar admisión").sum())
    ).reset_index()

    informe.append(resumen_anual.to_string(index=False))

    # 2. Métricas de Calidad de Datos Financieros y Duración
    informe.append("\n--- 2. CALIDAD DE DATOS ECONÓMICOS Y ESTRUCTURALES ---")

    if "valor_arancel_numerico" in df_hist.columns:
        aranceles_cero = (df_hist["valor_arancel_numerico"] == 0).sum()
        informe.append(f"- Total programas-año con Arancel $0: {aranceles_cero:,}")

    if "duracion_por_revisar" in df_hist.columns:
        duraciones_ext = df_hist["duracion_por_revisar"].sum()
        informe.append(f"- Total programas-año con duración atípica (<4 o >16 sem): {duraciones_ext:,}")

    # 3. Permanencia de Códigos Únicos a lo largo del tiempo
    programas_unicos = df_hist["codigo_unico"].nunique()
    inst_unicas = df_hist["nomb_inst"].nunique()
    informe.append("\n--- 3. DIMENSIÓN DEL PANEL ---")
    informe.append(f"- Total de Instituciones distintas observadas: {inst_unicas:,}")
    informe.append(f"- Total de Códigos Únicos de programa observados: {programas_unicos:,}")

    # Promedio de apariciones por programa
    apariciones = df_hist.groupby("codigo_unico")["cat_periodo"].nunique()
    informe.append(f"- Promedio de años que permanece activo un programa: {apariciones.mean():.1f} años")

    texto_final = "\n".join(informe)
    print(texto_final)

    # Guardar en TXT
    ruta_txt_global = CARPETA_REPORTES / "diagnostico_historico_global_2007_2025.txt"
    ruta_txt_global.write_text(texto_final, encoding="utf-8")
    print(f"\nReporte histórico global guardado en: {ruta_txt_global.name}")
    return texto_final

# Ejecutar el diagnóstico global
