"""# Bloque 2: #
Define la función procesar_anio, encargada del ETL individual. Carga el CSV anual, filtra registros de Universidades y nivel de Pregrado, detecta e imputa valores nulos o códigos especiales de ingreso (1900, 9995, etc.), audita la presencia de identificadores únicos (MRUN), evalúa inconsistencias en aranceles o duraciones y exporta el resultado consolidado por programa en formato Parquet comprimido.
"""

def procesar_anio(
    ruta_csv, anio, carpeta_salida=CARPETA_SALIDA, encoding="utf-8"
):
  ruta_csv = Path(ruta_csv)
  salida = Path(carpeta_salida) / f"resumen_{anio}_provisional.parquet"

  if not ruta_csv.is_file():
    raise FileNotFoundError(f"No se encontró el CSV: {ruta_csv}")

  # 1. Cargar archivo preservando formatos originales
  datos = pd.read_csv(ruta_csv, sep=";", encoding=encoding, dtype="string")
  datos.columns = datos.columns.str.strip().str.lower()

  if datos.columns.duplicated().any():
    raise ValueError("Hay nombres de columnas duplicados en el CSV.")

  for columna in datos.columns:
    datos[columna] = datos[columna].str.strip().replace("", pd.NA)

  necesarias = [
      "cat_periodo",
      "codigo_unico",
      "mrun",
      "tipo_inst_1",
      "nivel_global",
      "anio_ing_carr_ori",
  ]
  faltantes = [c for c in necesarias if c not in datos.columns]
  if faltantes:
    raise ValueError(f"Faltan columnas necesarias: {faltantes}")

  filas_originales = len(datos)

  # 2. Filtrar Universidades y Pregrado
  filtro = (
      datos["tipo_inst_1"].str.casefold().eq("universidades")
      & datos["nivel_global"].str.casefold().eq("pregrado")
  ).fillna(False)

  base = datos.loc[filtro].copy()
  del datos, filtro
  gc.collect()

  if base.empty:
    raise ValueError("No se encontraron registros de universidades y pregrado.")

  base["cat_periodo"] = anio
  claves = ["cat_periodo", "codigo_unico"]

  # 3. Auditoría de primer ingreso
  ingreso = pd.to_numeric(base["anio_ing_carr_ori"], errors="coerce")
  es_nuevo = ingreso.eq(anio).fillna(False)
  por_revisar = (
      ingreso.isna()
      | ingreso.isin([1900, 9995, 9998, 9999])
      | ingreso.gt(anio)
      | ingreso.le(0)
      | ingreso.mod(1).ne(0)
  ).fillna(True)

  nuevos = base.loc[es_nuevo]

  # 4. Agrupaciones y conteos
  conteos = (
      nuevos.groupby(claves)
      .agg(
          registros_primer_ingreso=("codigo_unico", "size"),
          ingresantes_identificados=("mrun", "nunique"),
          registros_sin_mrun=("mrun", lambda s: s.isna().sum()),
      )
      .reset_index()
  )

  pendientes = (
      base.loc[por_revisar]
      .groupby(claves)
      .size()
      .rename("registros_ingreso_por_revisar")
      .reset_index()
  )

  resumen = base[claves].drop_duplicates().merge(
      conteos, on=claves, how="left", validate="one_to_one"
  ).merge(pendientes, on=claves, how="left", validate="one_to_one")

  columnas_conteo = [
      "registros_primer_ingreso",
      "ingresantes_identificados",
      "registros_sin_mrun",
      "registros_ingreso_por_revisar",
  ]
  resumen[columnas_conteo] = resumen[columnas_conteo].fillna(0).astype("int64")

  resumen["conteo_requiere_revision"] = (
      resumen["registros_sin_mrun"].gt(0)
      | resumen["registros_ingreso_por_revisar"].gt(0)
  )

  resumen["estado_conteo"] = "Sin incidencias detectadas"
  resumen.loc[
      resumen["registros_primer_ingreso"].eq(0), "estado_conteo"
  ] = "Cero observado: verificar admisión"
  resumen.loc[
      resumen["conteo_requiere_revision"], "estado_conteo"
  ] = "Pendiente de revisión"

  resumen["nuevos_ingresados_provisional"] = (
      resumen["ingresantes_identificados"]
      .astype("Int64")
      .where(resumen["estado_conteo"].eq("Sin incidencias detectadas"))
  )

  # 5. Atributos y detección de conflictos
  atributos = [
      "cod_inst",
      "nomb_inst",
      "cod_sede",
      "nomb_sede",
      "cod_carrera",
      "nomb_carrera",
      "version",
      "tipo_inst_1",
      "tipo_inst_2",
      "tipo_inst_3",
      "nivel_global",
      "nivel_carrera_1",
      "nivel_carrera_2",
      "tipo_plan_carr",
      "jornada",
      "modalidad",
      "vigencia_carrera",
      "region_sede",
      "provincia_sede",
      "comuna_sede",
      "area_conocimiento",
      "area_carrera_generica",
      "dur_total_carr",
      "valor_arancel",
      "valor_matricula",
      "formato_valores",
      "acreditada_carr",
      "acreditada_inst",
      "acre_inst_anio",
  ]

  ausentes = [c for c in atributos if c not in base.columns]
  for columna in ausentes:
    base[columna] = pd.Series(pd.NA, index=base.index, dtype="string")

  grupos = base.groupby(claves)
  distintos = grupos[atributos].nunique(dropna=True)
  valores = grupos[atributos].first().mask(distintos.gt(1))
  marcas = distintos.gt(1).add_suffix("_conflicto")

  resumen = resumen.merge(
      valores.join(marcas).reset_index(),
      on=claves,
      how="left",
      validate="one_to_one",
  )

  # 6. Diagnóstico de campos numéricos
  columnas_numericas = [
      "valor_arancel",
      "valor_matricula",
      "dur_total_carr",
      "acre_inst_anio",
  ]
  for columna in columnas_numericas:
    texto = resumen[columna].astype("string")
    interpretable = texto.str.fullmatch(r"[+-]?\d+(?:\.0+)?", na=False)
    resumen[f"{columna}_numerico"] = pd.to_numeric(
        texto.where(interpretable), errors="coerce"
    ).astype("Float64")
    resumen[f"{columna}_faltante"] = texto.isna()
    resumen[f"{columna}_formato_por_revisar"] = texto.notna() & ~interpretable

  duracion = resumen["dur_total_carr_numerico"]
  resumen["duracion_por_revisar"] = (
      duracion.isna() | duracion.lt(4) | duracion.gt(16)
  ).fillna(True)
  resumen["archivo_origen"] = ruta_csv.name

  # Guardar archivo Parquet
  resumen.to_parquet(salida, index=False, compression="snappy")

  del grupos, nuevos, base
  gc.collect()

  return resumen, salida

"""# Bloque 3: #
Define la función exportar_diagnostico_ia, que recibe el DataFrame procesado y construye un informe estructurado en formato de texto plano (.txt). Muestra la distribución de programas según su estado de conteo, resumen global de ingresantes con y sin MRUN, banderas de anomalías financieras y una muestra del Top 10 de carreras que requieren auditoría manual.
"""

def exportar_diagnostico_ia(resumen, anio):
  """Genera un reporte sintético en texto plano para copiar/analizar."""
  informe = []
  informe.append(f"=== INFORME DE DIAGNÓSTICO DE DATOS ({anio}) ===")

  # 1. Estado general de los conteos
  informe.append("\n--- 1. ESTADO DE CONTEOS DE PROGRAMAS ---")
  estados = resumen["estado_conteo"].value_counts()
  for estado, cant in estados.items():
    informe.append(f"- {estado}: {cant} programas")

  # 2. Métricas globales de admisión
  informe.append("\n--- 2. MÉTRICAS GLOBALES DE ADMISIÓN ---")
  informe.append(f"- Total de programas observados: {len(resumen):,}")
  informe.append(
      "- Ingresantes identificados totales:"
      f" {resumen['ingresantes_identificados'].sum():,}"
  )
  informe.append(
      "- Registros de primer ingreso sin MRUN:"
      f" {resumen['registros_sin_mrun'].sum():,}"
  )
  informe.append(
      "- Registros con ingreso por revisar:"
      f" {resumen['registros_ingreso_por_revisar'].sum():,}"
  )

  # 3. Detección de anomalías en montos y duraciones
  informe.append("\n--- 3. DETECCIÓN DE ANOMALÍAS DE DATO Y FORMATO ---")
  for col, desc in [
      ("valor_arancel_cero", "Aranceles informados en $0"),
      ("valor_arancel_negativo", "Aranceles con valores negativos"),
      ("duracion_por_revisar", "Duraciones fuera de rango (menos de 4 o más de 16 semestres)"),
      ("unidad_monetaria_no_informada", "Programas sin formato de valor informados"),
  ]:
    if col in resumen.columns:
      informe.append(f"- {desc}: {resumen[col].sum()} programas")

  # 4. Muestra de programas que requieren revisión
  pendientes = resumen[resumen["estado_conteo"] != "Sin incidencias detectadas"]
  if not pendientes.empty:
    informe.append(
        "\n--- 4. MUESTRA DE PROGRAMAS QUE REQUIEREN REVISIÓN (Top 10) ---"
    )
    cols_mostrar = [
        c
        for c in [
            "codigo_unico",
            "nomb_inst",
            "nomb_carrera",
            "estado_conteo",
            "registros_sin_mrun",
            "registros_ingreso_por_revisar",
        ]
        if c in resumen.columns
    ]
    informe.append(pendientes[cols_mostrar].head(10).to_string(index=False))

  texto_final = "\n".join(informe)
  print(texto_final)
  return texto_final

"""# Bloque 4: #
Escanea la carpeta de entrada buscando todos los archivos .csv, extrae el año correspondiente mediante expresiones regulares (re) y ejecuta secuencialmente la función de limpieza (procesar_anio) y la de informe (exportar_diagnostico_ia). Guarda los archivos .parquet y los reportes .txt individuales para cada año detectado.
"""

import re
from pathlib import Path

# Carpeta para guardar los reportes de diagnóstico en texto plano
CARPETA_REPORTES = BASE_DIR / "reportes_diagnostico"
CARPETA_REPORTES.mkdir(parents=True, exist_ok=True)

# Buscar todos los archivos .csv en la carpeta matriculaaaas
archivos_csv = sorted(CARPETA_CSV.glob("*.csv"))

if not archivos_csv:
  print(f"No se encontraron archivos .csv en {CARPETA_CSV}")
else:
  print(f"Se encontraron {len(archivos_csv)} archivos CSV para procesar.\n")

# Bucle automático para procesar cada año
for archivo in archivos_csv:
  # Extraer el año real del dataset (el número de 4 dígitos antes de _PUBL)
  coincidencia = re.search(r"_(\d{4})_PUBL", archivo.name)

  if not coincidencia:
    # Alternativa si el archivo no tiene _PUBL: tomar la última secuencia de 4 dígitos
    todos_los_anios = re.findall(r"(?:19|20)\d{2}", archivo.name)
    if len(todos_los_anios) >= 2:
      anio = int(todos_los_anios[-1])  # El segundo año es el del dataset
    elif todos_los_anios:
      anio = int(todos_los_anios[0])
    else:
      print(
          "No se pudo identificar el año en el archivo:"
          f" {archivo.name}. Se omite."
      )
      continue
  else:
    anio = int(coincidencia.group(1))

  print("=" * 60)
  print(f"PROCESANDO AÑO REVELADO: {anio} | Archivo: {archivo.name}")
  print("=" * 60)

  try:
    # 1. Procesar el CSV y guardar el Parquet
    df_resumen, ruta_parquet = procesar_anio(ruta_csv=archivo, anio=anio)

    # 2. Generar el informe en texto
    informe_texto = exportar_diagnostico_ia(df_resumen, anio)

    # 3. Guardar el informe de diagnóstico por separado (.txt)
    ruta_txt = CARPETA_REPORTES / f"diagnostico_{anio}.txt"
    ruta_txt.write_text(informe_texto, encoding="utf-8")

    print(f"\nAño {anio} completado exitosamente.")
    print(f"   └─ Parquet: {ruta_parquet.name}")
    print(f"   └─ Reporte TXT: {ruta_txt.name}\n")

  except Exception as e:
    print(f"Error al procesar el año {anio} ({archivo.name}): {e}\n")

print("=" * 60)
print("¡Proceso finalizado! Todos los reportes individuales se guardaron en:")
print(f"   {CARPETA_REPORTES}")

